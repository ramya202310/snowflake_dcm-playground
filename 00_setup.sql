USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DCM_DEVELOPER;
GRANT ROLE DCM_DEVELOPER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE DCM_DEVELOPER TO USER IDENTIFIER($my_user);

GRANT CREATE DATABASE  ON ACCOUNT TO ROLE DCM_DEVELOPER;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE DCM_DEVELOPER;
GRANT CREATE ROLE      ON ACCOUNT TO ROLE DCM_DEVELOPER;

USE ROLE DCM_DEVELOPER;

CREATE DATABASE IF NOT EXISTS DCM_ADMIN;
CREATE SCHEMA   IF NOT EXISTS DCM_ADMIN.PROJECTS;

CREATE DCM PROJECT IF NOT EXISTS DCM_ADMIN.PROJECTS.PLAYGROUND_DEV
    COMMENT = 'Ramya DCM playground - DEV';

-- copy this into manifest.yml
SELECT CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS account_identifier;
