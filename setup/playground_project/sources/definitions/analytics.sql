DEFINE VIEW PLAYGROUND{{env_suffix}}.ANALYTICS.CUSTOMER_ORDER_SUMMARY
COMMENT = 'Order totals per customer'
AS
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    c.COUNTRY,
    COUNT(o.ORDER_ID) AS ORDER_COUNT,
    SUM(o.AMOUNT)     AS TOTAL_AMOUNT
FROM PLAYGROUND{{env_suffix}}.RAW.CUSTOMERS c
LEFT JOIN PLAYGROUND{{env_suffix}}.RAW.ORDERS o
    ON c.CUSTOMER_ID = o.CUSTOMER_ID
GROUP BY c.CUSTOMER_ID, c.CUSTOMER_NAME, c.COUNTRY;