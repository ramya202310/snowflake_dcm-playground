USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DCM_DEPLOYER;
GRANT ROLE DCM_DEPLOYER TO ROLE SYSADMIN;

SET my_user = CURRENT_USER();
GRANT ROLE DCM_DEPLOYER TO USER IDENTIFIER($my_user);

GRANT CREATE DATABASE  ON ACCOUNT TO ROLE DCM_DEPLOYER;
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE DCM_DEPLOYER;
GRANT CREATE ROLE      ON ACCOUNT TO ROLE DCM_DEPLOYER;

USE ROLE DCM_DEPLOYER;

CREATE DATABASE IF NOT EXISTS DCM_RS;
CREATE SCHEMA   IF NOT EXISTS DCM_RS.PROJECTS;

CREATE DCM PROJECT IF NOT EXISTS DCM_RS.PROJECTS.PLAYGROUND_DEV
    COMMENT = 'Ramya DCM playground - DEV';

-- copy this into manifest.yml
SELECT CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS account_identifier;
